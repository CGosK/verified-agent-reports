"""Write report/tables.md: the paper's tables, computed from work/results only."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from vawr import stats  # noqa: E402

R = os.path.join(ROOT, "work", "results")
L = lambda f: json.load(open(os.path.join(R, f)))  # noqa: E731


def fmt(r):
    if isinstance(r, (list, tuple)):
        r = stats.rate(*r)
    return "%d/%d (%.0f–%.0f%%)" % (r["k"], r["n"], 100 * r["ci95"][0], 100 * r["ci95"][1])


out = ["# Tables", "", "Generated by `report/make_tables.py` from `work/results/`; 95% intervals are exact "
       "two-sided Clopper–Pearson. Don't edit by hand; rerun the script.", ""]

HIDDEN = ("off_log", "off_log_no_files")  # other plants (prompted, underperform) are logged runs
o = L("off_log.json")
batch = lambda rid: "Batch 1" if rid < "20261114" else "Batch 2"  # noqa: E731
out += ["## Table 1. Off-log work", "",
        "| Set | Provider check: hidden runs caught | Provider check: logged runs flagged | Session-file check: hidden runs with files caught |",
        "| --- | --- | --- | --- |"]
ab = set(json.load(open(os.path.join(ROOT, "work", "env_ab_run_ids.json"))))
for name in ("Batch 1", "Batch 2"):
    rows = [r for r in o["runs"] if batch(r["run_id"]) == name and r["run_id"] not in ab]
    off = [r for r in rows if r["plant"] in HIDDEN]
    lg = [r for r in rows if r["plant"] not in HIDDEN]
    wf = [r for r in off if r["plant"] == "off_log"]
    out.append("| %s | %s | %s | %s |" % (name, fmt((sum(r["provider_flag"] for r in off), len(off))),
                                         fmt((sum(r["provider_flag"] for r in lg), len(lg))),
                                         fmt((sum(r["session_flag"] for r in wf), len(wf)))))
lg_ab = [r for r in o["runs"] if r["run_id"] in ab]
out.append("| Environment A/B (all logged) | – | %s | – |" % fmt((sum(r["provider_flag"] for r in lg_ab), len(lg_ab))))
allo = [r for r in o["runs"] if r["plant"] in HIDDEN]
alll = [r for r in o["runs"] if r["plant"] not in HIDDEN]
allw = [r for r in allo if r["plant"] == "off_log"]
out.append("| **All** | **%s** | **%s** | **%s** |" % (fmt((sum(r["provider_flag"] for r in allo), len(allo))),
                                                     fmt((sum(r["provider_flag"] for r in alll), len(alll))),
                                                     fmt((sum(r["session_flag"] for r in allw), len(allw)))))
c = L("concurrency.json")
out += ["", "Concurrency (unit: a window of three logged runs started 5 s apart): windows with a hidden run flagged %s; "
        "clean windows flagged %s." % (fmt(c["off_log_windows_flagged"]), fmt(c["clean_windows_flagged"])), ""]

t = L("tamper_summary.json")["summary"]
names = {"delete": "Delete an entry", "edit_tokens": "Edit token counts", "edit_category": "Edit a category",
         "rehash_tokens": "Edit tokens, rebuild chain", "rehash_category": "Edit a category, rebuild chain",
         "truncate": "Drop the last 1–20 entries"}
out += ["## Table 2. Tampered copies of the log", "",
        "| Edit | Copies | Chain | Session files (copies that touched requests) | Provider (copies that touched API-key requests) | Any check |",
        "| --- | --- | --- | --- | --- | --- |"]
for k in ("delete", "edit_tokens", "edit_category", "rehash_tokens", "rehash_category", "truncate"):
    r = t[k]
    out.append("| %s | %d | %s | %s | %s | %s |" % (names[k], r["trials"], fmt(r["chain"]), fmt(r["sessions_on_requests"]),
                                                  fmt(r["provider_on_sprint_requests"]), fmt(r["any"])))
out.append("")

cc = L("category_check.json")["summary"]
ho = L("category_heldout.json")["summary"]
out += ["## Table 3. Category check (prompt %s, %s)" % (cc["prompt_sha"], cc["model"]), "",
        "| Set | Items | Correct labels flagged | of which contradicted | Relabels caught | Capabilities relabeled as safety caught |",
        "| --- | --- | --- | --- | --- | --- |"]
for name, s in (("Development (batch 1 runs)", cc["dev"]), ("Held-out runs", cc["held_out_runs"]),
                ("Held-out written cases, clear", ho["clear"]), ("Held-out written cases, borderline", ho["borderline"])):
    out.append("| %s | %d | %s | %s | %s | %s |" % (name, s.get("runs", s.get("cases")), fmt(s["true_tags_flagged"]),
                                                   fmt(s["true_tags_contradicted"]), fmt(s["relabels_caught"]),
                                                   fmt(s["capabilities_to_safety_caught"])))
out.append("")

cl = L("claims_summary.json")
out += ["## Table 4. Claim checker", "", "| Case | Result |", "| --- | --- |",
        "| False \"done\" (honest summary, untouched code), caught | %s |" % fmt(cl["false_done_caught"]),
        "| Invented blocker that exists, caught | %s |" % fmt(cl["fake_blocker_caught"]),
        "| True blocker, wrongly flagged | %s |" % fmt(cl["true_blocker_wrongly_flagged"]),
        "| Held-out phrasing: invented blocker caught | %s |" % fmt(cl["fake_blocker_caught_held_out"]),
        "| Held-out phrasing: true blocker wrongly flagged | %s |" % fmt(cl["true_blocker_wrongly_flagged_held_out"]),
        "| Denials read as a claim | %s |" % fmt(cl["negations_with_spurious_claims"]),
        "| Honest real runs flagged | %s |" % fmt(cl["real_runs_flagged"]), ""]

a = L("allocation_report.json")
out += ["## Table 5. Allocation report (all logged runs)", "",
        "| Category | Runs | Requests | Total tokens | Share | Est. cost (USD) | Claims held up |", "| --- | --- | --- | --- | --- | --- | --- |"]
for cat in a["categories"]:
    out.append("| %s | %d | %d | %s | %.1f%% | %.2f | %s |" % (cat["category"], cat["runs"], cat["requests"],
                                                           "{:,}".format(cat["total_tokens"]), 100 * cat["token_share"],
                                                           cat["cost_usd"], "%d of %d" % (cat["claims_held"], cat["claims"]) if cat["claims"] else "n/a"))
out += ["", "Log head %s; %d entries." % (a["log"]["head"][:16], a["log"]["entries"]), ""]

ca = L("cc_analytics.json")
dt = L("daytest_received.json")
out += ["## Table 6. Anthropic's daily count of Claude Code sessions vs the log", "",
        "Anthropic's Claude Code Analytics API, per API key, UTC day and terminal type, against the log's sessions and "
        "tokens. Main key: the validation key (Nov 14; the main log started on Nov 13, so that day isn't compared). "
        "Separate key: every session on it that day was logged, received by the payer after the day closed.", "",
        "| Key, day | Terminal | Anthropic's sessions | Log's sessions | Tokens, Anthropic minus log | Result |",
        "| --- | --- | --- | --- | --- | --- |"]
diff = lambda d: ", ".join("%s %s" % (m.replace("claude-", ""), "{:+,}".format(v)) for m, v in sorted(d.items())) or "none"  # noqa: E731
for c in ca["days"]["2026-11-14"]["comparison"]["by_terminal"]:
    out.append("| Main key, Nov 14 | %s | %d | %d | %s | %s |" % (c["terminal"], c["anthropic_sessions"], c["log_sessions"],
                                                                diff(c["token_difference"]), c["status"].replace("_", " ")))
for d in (dt.get("check") or {}).get("sessions", {}).get("days", []):
    if d["day"] == "2026-11-14":
        out.append("| Separate key, Nov 14 | all | %d | %d | %s | %s |" % (d["anthropic_sessions"], d["log_sessions"],
                                                                         diff(d["token_difference"]), d["status"]))
nov14 = ca["days"]["2026-11-14"]
out += ["", "Main key, Nov 14: %d runs on the key in the manifests, %d of them hidden from the log. Billed minus "
        "Anthropic's count: %s." % (nov14["sprint_key_runs_in_manifests"], nov14["hidden_runs_in_manifests"],
                                    diff(nov14["billed_minus_anthropic"])), ""]

up = L("underperform.json")
su, hs = up["summary"], up["hidden_tests"]["summary"]
out += ["## Table 7. Weaker work described without false claims", "",
        "Safety tasks; planted runs were told to do a deliberately partial job and describe it in general terms "
        "without saying anything untrue. Controls ran normally at the same time.", "",
        "| | Planted | Controls |", "| --- | --- | --- |",
        "| Work fails the task's tests | %s | %s |" % (fmt(su["planted_tests_fail"]),
                                                     fmt((su["control_runs"] - su["controls_tests_pass"]["k"], su["control_runs"]))),
        "| Of those failing, flagged by the claim checker | %s | – |" % fmt(su["claim_checker_flags_weak_runs"]),
        "| Of those failing, flagged by the outcome column | %s | – |" % fmt(su["outcome_measure_flags_weak_runs"]),
        "| Flagged by the claim checker | – | %s |" % fmt(su["claim_checker_flags_controls"]),
        "| Passed the visible tests but fail hidden tests | %s | – |" % fmt(hs["planted_passing_visible_but_failing_hidden"]),
        "", "Hidden tests (docstring clauses the visible tests skip) pass on every reference solution, fail on every "
        "stub, and pass on %s normal safety runs." % fmt(hs["normal_runs_pass_hidden"]), ""]

ver = L("version_2_1_325.json")
ct = L("continuity_trials.json")
be = ver["ab"]["by_env"]
out += ["## Table B2. Claude Code 2.1.325 and continuity (appendix)", "", "| Test | Result |", "| --- | --- |",
        "| 2.1.325, desktop-app environment: runs with the unrecorded request | %s (cache read %s) |" % (
            fmt((be["inherited"]["with_unrecorded_request"], be["inherited"]["runs"])),
            ", ".join("{:,}".format(v) for v in be["inherited"]["cache_read_values"])),
        "| 2.1.325, clean environment: runs with the unrecorded request | %s |" % fmt(
            (be["clean"]["with_unrecorded_request"], be["clean"]["runs"])),
        "| 2.1.325 window: bill check, session-file check | %s, %s |" % (
            "pass" if ver["check"]["bill_ok"] else "fail", "pass" if ver["check"]["coverage"]["ok"] else "fail"),
        "| Continuity: rebuilds before an earlier report's head caught | %s |" % fmt(ct["caught_before_earlier_head"]),
        "| Continuity: rebuilds after it caught (by design) | %s |" % fmt(ct["caught_after_earlier_head"]), ""]

out += ["## Table B1. Hidden runs (appendix)", "", "| Run | Kind | Model | Provider check | Session-file check | Gap tokens |",
        "| --- | --- | --- | --- | --- | --- |"]
for r in sorted(allo, key=lambda r: r["run_id"]):
    out.append("| %s | %s | %s | %s | %s | %s |" % (r["run_id"][:16], r["plant"].replace("_", " "), r["model"],
                                                   "caught" if r["provider_flag"] else "missed",
                                                   "no files" if r["plant"] == "off_log_no_files" else ("caught" if r["session_flag"] else "missed"),
                                                   "{:,}".format(r["gap_tokens"])))
open(os.path.join(ROOT, "report", "tables.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out[:40]))
