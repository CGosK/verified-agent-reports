class SessionFilesTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.project = os.path.join(self.tmp.name, "proj")

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, sid, entries, subagent=None):
        path = os.path.join(self.project, sid + ".jsonl")
        if subagent:
            path = os.path.join(self.project, sid, "subagents", subagent + ".jsonl")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as fh:
            for e in entries:
                fh.write(json.dumps(e) + "\n")
            fh.write("not json\n")
        return path


class WorkFromSessionTest(SessionFilesTest):
    def setUp(self):
        super().setUp()
        self.path = self.write("s1", MAIN)
        self.write("s1", SUBAGENT, subagent="agent-a1")
        self.prompt, self.diff = sc.work_from_session(self.path)

    def test_prompt_is_typed_text_in_order(self):
        p = self.prompt
        for typed in ("Add a refusal metric", "Also handle empty lists", "Fix it",
                      "Explain what <system-reminder> tags are"):
            self.assertIn(typed, p)
        self.assertLess(p.index("Add a refusal"), p.index("Also handle"))
        self.assertLess(p.index("Also handle"), p.index("Fix it"))

    def test_prompt_skips_tool_results_reminders_and_noise(self):
        for noise in ("secret reminder", "more noise", "file text from a tool result", "Caveat",
                      "/clear", "background job", "interrupted", "Subagent instructions",
                      "String to replace"):
            self.assertNotIn(noise, self.prompt)

    def test_edits_become_a_diff_with_paths_relative_to_cwd(self):
        d = self.diff
        self.assertIn("--- a/evals/refusals.py\n+++ b/evals/refusals.py\n", d)
        self.assertIn("-    raise NotImplementedError\n+    if not records:\n+        return 0.0", d)
        self.assertIn("--- a/tests/test_refusals.py\n+++ b/tests/test_refusals.py\n", d)
        self.assertIn("+import unittest", d)
        self.assertIn("--- /elsewhere/notes.md\n+++ /elsewhere/notes.md\n", d)
        self.assertEqual(d.count("--- a/evals/refusals.py"), 1)
        self.assertEqual(d.count("+    if not records:"), 1)  # repeated block counted once

    def test_failed_edits_reads_and_claude_memory_are_left_out(self):
        self.assertNotIn("FAILED EDIT", self.diff)
        self.assertNotIn("file text from a tool result", self.diff)
        self.assertNotIn("MEMORY NOTE", self.diff)

    def test_subagent_edits_are_included_in_time_order(self):
        d = self.diff
        self.assertIn("--- a/evals/monitor.py\n+++ b/evals/monitor.py\n", d)
        self.assertIn("-THRESHOLD = 1\n+THRESHOLD = 2", d)
        self.assertIn("-pass\n+return flagged", d)
        # files appear in order of first touch across main and subagent files
        order = [d.index(h) for h in ("+++ b/evals/refusals.py", "+++ b/tests/test_refusals.py",
                                      "+++ b/evals/monitor.py", "+++ /elsewhere/notes.md")]
        self.assertEqual(order, sorted(order))

    def test_long_work_is_cut_without_losing_the_short_parts(self):
        big = "x" * 20000
        path = self.write("s2", [
            user(big), user("short second prompt"),
            tool_use("w1", "Write", {"file_path": CWD + "/big.py", "content": "\n".join([big] * 3)}),
            tool_use("w2", "Write", {"file_path": CWD + "/small.py", "content": "y = 1\n"},
                     ts="2026-11-13T10:00:01Z")])
        prompt, diff = sc.work_from_session(path)
        self.assertLessEqual(len(prompt), sc.MAX_PROMPT_CHARS)
        self.assertLessEqual(len(diff), category.MAX_DIFF_CHARS)
        self.assertIn("short second prompt", prompt)
        self.assertIn("+++ b/small.py\n@@ write (whole file) @@\n+y = 1", diff)
        self.assertIn("[... cut ...]", diff)


class BashWritesTest(unittest.TestCase):
    def writes(self, command):
        return sc._bash_writes(command, CWD)

    def test_heredoc_forms(self):
        self.assertEqual(self.writes("cat > labkit/a.py <<'EOF'\nimport re\nx = 1\nEOF\npython3 -m unittest t"),
                         [(CWD + "/labkit/a.py", False, "import re\nx = 1\n")])
        self.assertEqual(self.writes('cat >> notes.txt <<"END"\nmore\nEND'),
                         [(CWD + "/notes.txt", True, "more\n")])
        self.assertEqual(self.writes("cat <<EOF > b.py\ny = 2\nEOF"), [(CWD + "/b.py", False, "y = 2\n")])
        self.assertEqual(self.writes("tee -a c.py <<EOF >/dev/null\nz = 3\nEOF"),
                         [(CWD + "/c.py", True, "z = 3\n")])
        self.assertEqual(self.writes("tee d.py <<-EOF\n\tw = 4\n\tEOF"), [(CWD + "/d.py", False, "w = 4\n")])
        self.assertEqual(self.writes("cd sub && cat > h.py <<EOF\nv = 5\nEOF"),
                         [(CWD + "/sub/h.py", False, "v = 5\n")])
        self.assertEqual(self.writes("cat > /abs/one.py <<A\n1\nA\ncat > two.py <<B\n2\nB"),
                         [("/abs/one.py", False, "1\n"), (CWD + "/two.py", False, "2\n")])

    def test_echo_and_printf_with_one_redirect(self):
        self.assertEqual(self.writes('echo "x = 1" > e.py'), [(CWD + "/e.py", False, "x = 1\n")])
        self.assertEqual(self.writes("echo -n hi >> e2.txt"), [(CWD + "/e2.txt", True, "hi")])
        self.assertEqual(self.writes("printf 'a\\nb\\n' > f.txt"), [(CWD + "/f.txt", False, "a\nb\n")])
        self.assertEqual(self.writes("printf '%s\\n' one two > g.txt"),
                         [(CWD + "/g.txt", False, "one\ntwo\n")])

    def test_unreadable_commands_are_skipped(self):
        for cmd in ("cat <<EOF | python3\nprint(1)\nEOF",
                    "echo $(date) > i.txt", "echo `date` > i.txt", "echo $HOME > k.txt",
                    "echo hi | tee j.txt", "echo a 2>&1 > o.txt", "printf '%d\\n' 3 > p.txt",
                    "cat > n.py <<EOF\nunterminated",
                    # a heredoc body is not read as shell commands
                    "python3 - <<'EOF'\nopen('l.py', 'w').write('x')\necho no > m.txt\nEOF",
                    "ls -la", "echo 'unbalanced > q.txt"):
            self.assertEqual(self.writes(cmd), [], cmd)


def fake(calls):
    """A stand-in for the model call: safety when the task mentions refusals."""
    def classify_fn(task_prompt, diff):
        calls.append((task_prompt, diff))
        return {"category": "safety" if "refusal" in task_prompt else "other", "reason": "test"}
    return classify_fn


def boom(task_prompt, diff):
    raise AssertionError("the model should not be called")


class CheckSessionsTest(SessionFilesTest):
    def setUp(self):
        super().setUp()
        self.paths = [self.write("s1", MAIN),
                      self.write("s1", SUBAGENT, subagent="agent-a1"),
                      self.write("s2", [user("Tidy the date helpers")]),
                      self.write("s3", [user("noise only", isMeta=True)]),
                      self.write("s4", [user("Write the refusal docs")])]

    def test_rows_flags_and_verdicts(self):
        calls = []
        rows = sc.check_sessions(self.paths, {"s1": "safety", "s2": "capabilities"}, {}, fake(calls))
        got = [(r["run_id"], r["declared"], r["classified"], r["flagged"], r["verdict"]) for r in rows]
        self.assertEqual(got, [("s1", "safety", "safety", False, "confirmed"),
                               ("s2", "capabilities", "other", True, "unconfirmed"),
                               ("s4", "untagged", "safety", True, "contradicted")])
        self.assertEqual(len(calls), 3)  # no call for the subagent file or the empty session
        self.assertIn("+++ b/evals/monitor.py", calls[0][1])

    def test_verdicts_are_cached_by_session_and_content(self):
        cache = {}
        sc.check_sessions(self.paths, {"s1": "safety"}, cache, fake([]))
        prompt, diff = sc.work_from_session(self.paths[0])
        key = sc.cache_key("s1", prompt, diff)
        self.assertRegex(key, r"^session:s1:[0-9a-f]{12}$")
        self.assertIn("%s|%s" % (category.PROMPT_SHA, key), cache)
        rows = sc.check_sessions(self.paths, {"s1": "safety"}, cache, boom)
        self.assertEqual(rows[0]["classified"], "safety")

    def test_a_session_that_continues_is_checked_again(self):
        cache = {}
        sc.check_sessions(self.paths, {}, cache, fake([]))
        self.write("s2", [user("Tidy the date helpers"), user("now add refusal counts too")])
        calls = []
        rows = sc.check_sessions(self.paths, {}, cache, fake(calls))
        self.assertEqual(len(calls), 1)  # only s2 changed
        s2 = [r for r in rows if r["run_id"] == "s2"][0]  # row id stays the plain session id
        self.assertEqual(s2["classified"], "safety")


class BashInSessionTest(SessionFilesTest):
    def test_bash_writes_join_the_diff(self):
        memory = shlex.quote(os.path.join(sc.CLAUDE_HOME, "projects", "p", "memory", "M.md"))
        path = self.write("s5", [
            user("Implement the LRU cache"),
            tool_use("b1", "Bash", {"command": "cat > labkit/model/cache.py <<'EOF'\nclass LRUCache:\n"
                                               "    pass\nEOF\npython3 -m unittest"}),
            result("b1", "Exit code 1\nFAILED (failures=1)", error=True),  # ran, then tests failed
            tool_use("b2", "Bash", {"command": "echo DENIED > z.txt"}, ts="2026-11-13T10:00:01Z"),
            result("b2", "Permission for this tool use was denied.", error=True),
            tool_use("b3", "Bash", {"command": "echo x > /dev/null; cat > %s <<EOF\nMEMORY\nEOF" % memory},
                     ts="2026-11-13T10:00:02Z"),
            tool_use("b4", "Bash", {"command": "echo hi >> s.txt"}, ts="2026-11-13T10:00:03Z",
                     cwd=CWD + "/sub"),
        ])
        _, diff = sc.work_from_session(path)
        self.assertIn("--- a/labkit/model/cache.py\n+++ b/labkit/model/cache.py\n@@ bash write @@\n"
                      "+class LRUCache:\n+    pass\n", diff)
        self.assertIn("+++ b/sub/s.txt\n@@ bash write (append) @@\n+hi", diff)
        for left_out in ("DENIED", "MEMORY", "/dev/null"):
            self.assertNotIn(left_out, diff)


