def user(content, **extra):
    e = {"type": "user", "cwd": CWD, "message": {"role": "user", "content": content}}
    e.update(extra)
    return e


def tool_use(tid, name, inp, ts="2026-11-13T10:00:00Z", **extra):
    e = {"type": "assistant", "cwd": CWD, "timestamp": ts,
         "message": {"role": "assistant",
                     "content": [{"type": "tool_use", "id": tid, "name": name, "input": inp}]}}
    e.update(extra)
    return e


def result(tid, text="ok", error=False):
    block = {"type": "tool_result", "tool_use_id": tid, "content": text}
    if error:
        block["is_error"] = True
    return user([block], toolUseResult={"stdout": text})


def edit(path, old, new):
    return {"file_path": path, "old_string": old, "new_string": new}


